#!/usr/bin/env python3
"""
Turns the PowerShell scripts that MCP tools run in a guest
(src/app_win/mcp_scripts/*.ps1) into C string constants in
src/app_win/mcp_scripts.h. Run it after editing a script:

    python tools/gen-mcp-scripts.py

Comment lines and blank lines are left out. `--check` exits 1 when the
header is not up to date (nothing is written).
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "src", "app_win", "mcp_scripts")
OUT = os.path.join(ROOT, "src", "app_win", "mcp_scripts.h")


def c_literal(line):
    out = []
    for ch in line:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("    ")
        elif ord(ch) < 0x20 or ord(ch) > 0x7E:
            raise SystemExit("non-ASCII character in a script: %r" % line)
        else:
            out.append(ch)
    return '    "' + "".join(out) + '\\n"'


def main():
    parts = [
        "/* Generated by tools/gen-mcp-scripts.py from src/app_win/mcp_scripts/*.ps1.",
        "   Do not edit: change the .ps1 and run the generator. */",
        "#ifndef MCP_SCRIPTS_H",
        "#define MCP_SCRIPTS_H",
        "",
    ]
    for name in sorted(os.listdir(SRC)):
        if not name.endswith(".ps1"):
            continue
        with open(os.path.join(SRC, name), encoding="utf-8") as f:
            lines = [l.rstrip() for l in f.read().splitlines()]
        lines = [l for l in lines if l.strip() and not l.lstrip().startswith("#")]
        parts.append("static const char g_ps_%s[] =" % name[:-4])
        parts.extend(c_literal(l) for l in lines)
        parts[-1] += ";"
        parts.append("")
    parts.append("#endif /* MCP_SCRIPTS_H */")
    text = "\r\n".join(parts) + "\r\n"
    current = None
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8", newline="") as f:
            current = f.read()
    if "--check" in sys.argv:
        if current != text:
            print("src/app_win/mcp_scripts.h is out of date: run python tools/gen-mcp-scripts.py")
            return 1
        return 0
    if current != text:
        with open(OUT, "w", encoding="utf-8", newline="") as f:
            f.write(text)
    print("mcp_scripts.h: %d bytes" % len(text))
    return 0


if __name__ == "__main__":
    sys.exit(main())
